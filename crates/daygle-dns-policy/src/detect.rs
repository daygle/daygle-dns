//! Name-based threat detectors: they judge a query name by its letters
//! alone, so they run on the query path at no cost beyond a few table
//! lookups.
//!
//! - **IDN homographs**: internationalized names that imitate a Latin one
//!   with look-alike letters from another script (`аррӏе.com` in Cyrillic),
//!   either by mixing scripts in one label or by spelling a whole label in
//!   another script's Latin look-alikes outside that script's own TLDs.
//! - **DGA domains**: names made up by malware's domain generation
//!   algorithms to find its command-and-control servers. The registered
//!   label's letter pairs are scored against how often they occur in the
//!   names of popular sites ([`crate::dga_model`]); random strings score far
//!   lower than words, brands and abbreviations.

use crate::dga_model::BIGRAM_LOG2_CENTI;

/// Second-level labels that are part of a country's public suffix
/// (`example.co.uk`); kept in step with `scripts/gen-dga-model.py`.
const SECOND_LEVEL: &[&str] = &[
    "co", "com", "net", "org", "gov", "edu", "ac", "or", "ne", "go", "gob", "nic", "mil", "ltd",
    "plc", "sch", "nom", "info", "biz", "gen", "web", "in",
];

/// Fewest letters a label needs before the DGA score means anything:
/// shorter random and real names look alike.
pub const DGA_MIN_LETTERS: usize = 10;

/// The mean letter-pair log-probability (base 2, in hundredths) below which
/// a label is taken to be generated. Measured on half a million popular
/// domains not used to build the model, it flags about 0.02% of them (most
/// of which look generated themselves) and about 88% of random-letter names
/// of 10 to 20 letters.
pub const DGA_THRESHOLD_CENTI: i32 = -520;

/// The label a domain was registered as: `example` for `www.example.com`
/// and `shop.example.co.uk`. `None` for a single-label name.
pub fn registered_label(qname: &str) -> Option<&str> {
    let mut labels = qname.rsplit('.');
    let tld = labels.next()?;
    let second = labels.next()?;
    if tld.len() == 2 && SECOND_LEVEL.contains(&second) {
        if let Some(third) = labels.next() {
            return Some(third);
        }
    }
    Some(second)
}

/// The domain a name was registered as: `example.com` for
/// `www.example.com`, `example.co.uk` for `shop.example.co.uk`. `None` for
/// a single-label name.
pub fn registered_domain(qname: &str) -> Option<&str> {
    let label = registered_label(qname)?;
    // The label is a slice of `qname`: the domain starts where it does.
    let start = label.as_ptr() as usize - qname.as_ptr() as usize;
    Some(&qname[start..])
}

/// The DGA score of `label` (mean letter-pair log-probability in
/// hundredths of a bit), or `None` when the label is not one the score
/// suits: internationalized, hyphenated, mostly digits, or too short.
pub fn dga_score(label: &str) -> Option<i32> {
    if label.starts_with("xn--") || label.contains('-') || !label.is_ascii() {
        return None;
    }
    let digits = label.bytes().filter(u8::is_ascii_digit).count();
    if digits > label.len() / 3 {
        return None;
    }
    let symbols: Vec<usize> = std::iter::once(0)
        .chain(
            label
                .bytes()
                .filter(u8::is_ascii_alphabetic)
                .map(|b| (b.to_ascii_lowercase() - b'a') as usize + 1),
        )
        .chain(std::iter::once(0))
        .collect();
    if symbols.len() - 2 < DGA_MIN_LETTERS {
        return None;
    }
    let total: i32 = symbols
        .windows(2)
        .map(|pair| i32::from(BIGRAM_LOG2_CENTI[pair[0]][pair[1]]))
        .sum();
    Some(total / (symbols.len() as i32 - 1))
}

/// Whether `qname`'s registered label looks generated by a DGA.
pub fn is_dga(qname: &str) -> bool {
    registered_label(qname)
        .and_then(dga_score)
        .is_some_and(|score| score < DGA_THRESHOLD_CENTI)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Script {
    Latin,
    Greek,
    Cyrillic,
    Armenian,
}

fn script_of(c: char) -> Option<Script> {
    match c as u32 {
        0x61..=0x7A | 0xC0..=0x24F | 0x1E00..=0x1EFF => Some(Script::Latin),
        0x370..=0x3FF | 0x1F00..=0x1FFF => Some(Script::Greek),
        0x400..=0x52F | 0x1C80..=0x1C8F | 0x2DE0..=0x2DFF | 0xA640..=0xA69F => {
            Some(Script::Cyrillic)
        }
        0x530..=0x58F => Some(Script::Armenian),
        _ => None,
    }
}

/// Cyrillic letters that pass for Latin ones.
const CYRILLIC_LOOKALIKES: &str = "аысԁеԍһіюјӏорԗԛѕԝхуъьҽпгѵѡ";
/// Greek letters that pass for Latin ones.
const GREEK_LOOKALIKES: &str = "αικνορτυχ";

/// ASCII country-code TLDs where Cyrillic names are at home.
const CYRILLIC_TLDS: &[&str] = &[
    "ru", "su", "by", "ua", "kz", "bg", "rs", "mk", "mn", "kg", "tj", "uz", "me", "ba",
];
/// ASCII country-code TLDs where Greek names are at home.
const GREEK_TLDS: &[&str] = &["gr", "cy"];

/// Why `qname` looks like an IDN homograph, if it does.
pub fn homograph(qname: &str) -> Option<String> {
    let tld = qname.rsplit('.').next().unwrap_or(qname);
    let tld_unicode = decode_label(tld).unwrap_or_else(|| tld.to_string());
    let tld_script = tld_unicode.chars().find_map(script_of);
    let labels: Vec<&str> = qname.split('.').collect();
    let below_tld = &labels[..labels.len().saturating_sub(1)];
    for label in below_tld.iter().filter(|l| l.starts_with("xn--")) {
        let Some(unicode) = decode_label(label) else {
            continue;
        };
        let mut scripts: Vec<Script> = Vec::new();
        for script in unicode.chars().filter_map(script_of) {
            if !scripts.contains(&script) {
                scripts.push(script);
            }
        }
        if scripts.len() > 1 {
            return Some(format!(
                "'{unicode}' mixes letters from different alphabets"
            ));
        }
        let (lookalikes, native_tlds) = match scripts.first() {
            Some(Script::Cyrillic) => (CYRILLIC_LOOKALIKES, CYRILLIC_TLDS),
            Some(Script::Greek) => (GREEK_LOOKALIKES, GREEK_TLDS),
            _ => continue,
        };
        let native = native_tlds.contains(&tld) || tld_script == scripts.first().copied();
        let letters: Vec<char> = unicode
            .chars()
            .filter(|c| script_of(*c).is_some())
            .collect();
        if !native && !letters.is_empty() && letters.iter().all(|c| lookalikes.contains(*c)) {
            return Some(format!(
                "'{unicode}' is spelled entirely in letters that imitate Latin ones"
            ));
        }
    }
    None
}

/// The Unicode form of one punycode (`xn--`) label.
fn decode_label(label: &str) -> Option<String> {
    let encoded = label.strip_prefix("xn--")?;
    idna::punycode::decode_to_string(encoded)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ascii(name: &str) -> String {
        idna::domain_to_ascii(name).unwrap()
    }

    #[test]
    fn registered_labels() {
        assert_eq!(registered_label("www.example.com"), Some("example"));
        assert_eq!(registered_label("shop.example.co.uk"), Some("example"));
        assert_eq!(registered_label("example.co"), Some("example"));
        assert_eq!(registered_label("localhost"), None);
        assert_eq!(
            registered_domain("a.b.example.co.uk"),
            Some("example.co.uk")
        );
        assert_eq!(registered_domain("www.example.com"), Some("example.com"));
    }

    #[test]
    fn generated_names_are_flagged_and_real_ones_are_not() {
        for name in [
            "lqomwlpfnvbibkf.com",
            "xjkqpwzvbnmtrd.net",
            "www.qxvzkplmwbtr.org",
            "kfjdhqzxvbnw.ru",
        ] {
            assert!(is_dga(name), "{name}");
        }
        for name in [
            "www.stackoverflow.com",
            "googleusercontent.com",
            "d1a2b3c4d5e6f7.cloudfront.net",
            "dropboxusercontent.com",
            "msftconnecttest.com",
            "sharepointonline.com",
            "wikipedia.org",
            "theguardian.co.uk",
            "microsoftonline.com",
            "xiaohongshu.com",
            "short.com",
            "xn--80ak6aa92e.com",
            "aaaa-bbbb-cccc-dddd.com",
        ] {
            assert!(
                !is_dga(name),
                "{name}: {:?}",
                registered_label(name).and_then(dga_score)
            );
        }
    }

    #[test]
    fn homographs_are_flagged() {
        // Cyrillic а in an otherwise Latin label.
        assert!(homograph(&ascii("pаypal.com")).is_some());
        // A whole label in Cyrillic look-alikes, under .com.
        assert!(homograph(&ascii("аррӏе.com")).is_some());
        // Greek omicron among Latin letters.
        assert!(homograph(&ascii("gοogle.com")).is_some());
    }

    #[test]
    fn genuine_international_names_are_not() {
        for name in [
            "bücher.de",
            "münchen.de",
            "яндекс.рф",
            "пример.com",
            "аррӏе.ru",
            "ουρα.gr",
            "例え.jp",
            "example.com",
            "xn--zz.com",
        ] {
            let name = idna::domain_to_ascii(name).unwrap_or_else(|_| name.to_string());
            assert_eq!(homograph(&name), None, "{name}");
        }
    }
}
