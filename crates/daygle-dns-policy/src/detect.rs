/// Brands' own registered domains that would otherwise match.
const BRAND_DOMAINS: &[&str] = &[
    "halifax-online.co.uk",
    "rakuten-bank.co.jp",
    "yahoo-help.jp",
];

/// Character sequences that pass for others in a domain name.
const LOOKALIKE_CHARS: &[(&str, &str)] = &[
    ("rn", "m"),
    ("vv", "w"),
    ("0", "o"),
    ("1", "l"),
    ("3", "e"),
    ("5", "s"),
    ("4", "a"),
];

/// Whether `a` and `b` differ by exactly one edit: a letter added, removed,
/// changed, or two neighbours swapped.
fn one_edit_apart(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a == b || a.len().abs_diff(b.len()) > 1 {
        return false;
    }
    if a.len() == b.len() {
        let diff: Vec<usize> = (0..a.len()).filter(|&i| a[i] != b[i]).collect();
        return match diff.as_slice() {
            [_] => true,
            [i, j] => *j == i + 1 && a[*i] == b[*j] && a[*j] == b[*i],
            _ => false,
        };
    }
    let (short, long) = if a.len() < b.len() { (a, b) } else { (b, a) };
    let i = short.iter().zip(long).take_while(|(x, y)| x == y).count();
    short[i..] == long[i + 1..]
}

/// Why `qname` looks like it imitates a well-known brand, if it does: a
/// one-letter typo of the brand (`paypa.com`, `gooogle.com`), look-alike
/// characters (`app1e.com`, `rnicrosoft.com`), or the brand hyphenated with
/// a word phishing uses (`paypal-login.com`). The brands' own names, under
/// any TLD, are never matched.
pub fn typosquat(qname: &str) -> Option<String> {
    let domain = registered_domain(qname)?;
    let label = registered_label(qname)?;
    if BRAND_DOMAINS.contains(&domain) || label.starts_with("xn--") {
        return None;
    }
    let is_brand = |l: &str| BRANDS.iter().any(|(b, _)| *b == l);
    if is_brand(label) || is_brand(&label.replace('-', "")) {
        return None;
    }
    let mut plain = label.to_string();
    for (lookalike, real) in LOOKALIKE_CHARS {
        plain = plain.replace(lookalike, real);
    }
    if plain != label && plain.len() >= LOOKALIKE_MIN_LEN && is_brand(&plain) {
        return Some(format!(
            "'{label}' imitates '{plain}' with look-alike characters"
        ));
    }
    if let Some((brand, _)) = BRANDS
        .iter()
        .find(|(b, typo)| *typo && b.len() >= TYPO_MIN_LEN && one_edit_apart(label, b))
    {
        return Some(format!("'{label}' is one typo away from '{brand}'"));
    }
    let words: Vec<&str> = label.split('-').collect();
    if words.len() > 1 {
        if let Some(brand) = words
            .iter()
            .find(|w| w.len() >= LOOKALIKE_MIN_LEN && is_brand(w))
        {
            if words.iter().any(|w| PHISHING_WORDS.contains(w)) {
                return Some(format!(
                    "'{label}' pairs '{brand}' with a word phishing uses"
                ));
            }
        }
    }
    None
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Script {
    Latin,
    Greek,
    Cyrillic,
    Armenian,
}

fn script_of(c: char) -> Option<Script> {
    match c as u32 {
        0x61..=0x7A | 0xC0..=0x24F | 0x1E00..=0x1EFF => Some(Script::Latin),
        0x370..=0x3FF | 0x1F00..=0x1FFF => Some(Script::Greek),
        0x400..=0x52F | 0x1C80..=0x1C8F | 0x2DE0..=0x2DFF | 0xA640..=0xA69F => {
            Some(Script::Cyrillic)
        }
        0x530..=0x58F => Some(Script::Armenian),
        _ => None,
    }
}

/// Cyrillic letters that pass for Latin ones.
const CYRILLIC_LOOKALIKES: &str = "аысԁеԍһіюјӏорԗԛѕԝхуъьҽпгѵѡ";
/// Greek letters that pass for Latin ones.
const GREEK_LOOKALIKES: &str = "αικνορτυχ";

/// ASCII country-code TLDs where Cyrillic names are at home.
const CYRILLIC_TLDS: &[&str] = &[
    "ru", "su", "by", "ua", "kz", "bg", "rs", "mk", "mn", "kg", "tj", "uz", "me", "ba",
];
/// ASCII country-code TLDs where Greek names are at home.
const GREEK_TLDS: &[&str] = &["gr", "cy"];

/// Why `qname` looks like an IDN homograph, if it does.
pub fn homograph(qname: &str) -> Option<String> {
    let tld = qname.rsplit('.').next().unwrap_or(qname);
    let tld_unicode = decode_label(tld).unwrap_or_else(|| tld.to_string());
    let tld_script = tld_unicode.chars().find_map(script_of);
    let labels: Vec<&str> = qname.split('.').collect();
    let below_tld = &labels[..labels.len().saturating_sub(1)];
    for label in below_tld.iter().filter(|l| l.starts_with("xn--")) {
        let Some(unicode) = decode_label(label) else {
            continue;
        };
        let mut scripts: Vec<Script> = Vec::new();
        for script in unicode.chars().filter_map(script_of) {
            if !scripts.contains(&script) {
                scripts.push(script);
            }
        }
        if scripts.len() > 1 {
            return Some(format!(
                "'{unicode}' mixes letters from different alphabets"
            ));
        }
        let (lookalikes, native_tlds) = match scripts.first() {
            Some(Script::Cyrillic) => (CYRILLIC_LOOKALIKES, CYRILLIC_TLDS),
            Some(Script::Greek) => (GREEK_LOOKALIKES, GREEK_TLDS),
            _ => continue,
        };
        let native = native_tlds.contains(&tld) || tld_script == scripts.first().copied();
        let letters: Vec<char> = unicode
            .chars()
            .filter(|c| script_of(*c).is_some())
            .collect();
        if !native && !letters.is_empty() && letters.iter().all(|c| lookalikes.contains(*c)) {
            return Some(format!(
                "'{unicode}' is spelled entirely in letters that imitate Latin ones"
            ));
        }
    }
    None
}

/// The Unicode form of one punycode (`xn--`) label.
fn decode_label(label: &str) -> Option<String> {
    let encoded = label.strip_prefix("xn--")?;
    idna::punycode::decode_to_string(encoded)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ascii(name: &str) -> String {
        idna::domain_to_ascii(name).unwrap()
    }

    #[test]
    fn registered_labels() {
        assert_eq!(registered_label("www.example.com"), Some("example"));
        assert_eq!(registered_label("shop.example.co.uk"), Some("example"));
        assert_eq!(registered_label("example.co"), Some("example"));
        assert_eq!(registered_label("localhost"), None);
        assert_eq!(
            registered_domain("a.b.example.co.uk"),
            Some("example.co.uk")
        );
        assert_eq!(registered_domain("www.example.com"), Some("example.com"));
    }

    #[test]
    fn generated_names_are_flagged_and_real_ones_are_not() {
        for name in [
            "lqomwlpfnvbibkf.com",
            "xjkqpwzvbnmtrd.net",
            "www.qxvzkplmwbtr.org",
            "kfjdhqzxvbnw.ru",
        ] {
            assert!(is_dga(name), "{name}");
        }
        for name in [
            "www.stackoverflow.com",
            "googleusercontent.com",
            "d1a2b3c4d5e6f7.cloudfront.net",
            "dropboxusercontent.com",
            "msftconnecttest.com",
            "sharepointonline.com",
            "wikipedia.org",
            "theguardian.co.uk",
            "microsoftonline.com",
            "xiaohongshu.com",
            "short.com",
            "xn--80ak6aa92e.com",
            "aaaa-bbbb-cccc-dddd.com",
        ] {
            assert!(
                !is_dga(name),
                "{name}: {:?}",
                registered_label(name).and_then(dga_score)
            );
        }
    }

    #[test]
    fn typosquats_are_flagged() {
        for name in [
            "paypa1.com",
            "www.rnicrosoft.com",
            "gooogle.com",
            "faceboook.net",
            "linkdin.com",
            "amazom.co.uk",
            "paypal-login.com",
            "secure-apple-id.net",
            "app1e.com",
        ] {
            assert!(typosquat(name).is_some(), "{name}");
        }
    }

    #[test]
    fn real_and_unrelated_names_are_not_typosquats() {
        for name in [
            "paypal.com",
            "www.google.co.uk",
            "google.de",
            "t-mobile.com",
            "wal-mart.com",
            "halifax-online.co.uk",
            "pcloud.com",
            "finance.ua",
            "tiktak.si",
            "applesauce.com",
            "goals.com",
            "ample.com",
            "apple-pie-recipes.com",
            "example.com",
            "dhl.de",
        ] {
            assert_eq!(typosquat(name), None, "{name}");
        }
        assert!(one_edit_apart("google", "gogle"));
        assert!(one_edit_apart("google", "goolge"));
        assert!(!one_edit_apart("google", "goggle1"));
    }

    #[test]
    fn homographs_are_flagged() {
        // Cyrillic а in an otherwise Latin label.
        assert!(homograph(&ascii("pаypal.com")).is_some());
        // A whole label in Cyrillic look-alikes, under .com.
        assert!(homograph(&ascii("аррӏе.com")).is_some());
        // Greek omicron among Latin letters.
        assert!(homograph(&ascii("gοogle.com")).is_some());
    }

    #[test]
    fn genuine_international_names_are_not() {
        for name in [
            "bücher.de",
            "münchen.de",
            "яндекс.рф",
            "пример.com",
            "аррӏе.ru",
            "ουρα.gr",
            "例え.jp",
            "example.com",
            "xn--zz.com",
        ] {
            let name = idna::domain_to_ascii(name).unwrap_or_else(|_| name.to_string());
            assert_eq!(homograph(&name), None, "{name}");
        }
    }
}
