//! Name-based threat detectors: they judge a query name by its letters
//! alone, so they run on the query path at no cost beyond a few table
//! lookups.
//!
//! - **IDN homographs**: internationalized names that imitate a Latin one
//!   with look-alike letters from another script (`аррӏе.com` in Cyrillic),
//!   either by mixing scripts in one label or by spelling a whole label in
//!   another script's Latin look-alikes outside that script's own TLDs.
//! - **DGA domains**: names made up by malware's domain generation
//!   algorithms to find its command-and-control servers. The registered
//!   label's letter pairs are scored against how often they occur in the
//!   names of popular sites ([`crate::dga_model`]); random strings score far
//!   lower than words, brands and abbreviations.

use crate::dga_model::BIGRAM_LOG2_CENTI;

/// Second-level labels that are part of a country's public suffix
/// (`example.co.uk`); kept in step with `scripts/gen-dga-model.py`.
const SECOND_LEVEL: &[&str] = &[
    "co", "com", "net", "org", "gov", "edu", "ac", "or", "ne", "go", "gob", "nic", "mil", "ltd",
    "plc", "sch", "nom", "info", "biz", "gen", "web", "in",
];

/// Fewest letters a label needs before the DGA score means anything:
/// shorter random and real names look alike.
pub const DGA_MIN_LETTERS: usize = 10;

/// The mean letter-pair log-probability (base 2, in hundredths) below which
/// a label is taken to be generated. Measured on half a million popular
/// domains not used to build the model, it flags about 0.02% of them (most
/// of which look generated themselves) and about 88% of random-letter names
/// of 10 to 20 letters.
pub const DGA_THRESHOLD_CENTI: i32 = -520;

/// The label a domain was registered as: `example` for `www.example.com`
/// and `shop.example.co.uk`. `None` for a single-label name.
pub fn registered_label(qname: &str) -> Option<&str> {
    let mut labels = qname.rsplit('.');
    let tld = labels.next()?;
    let second = labels.next()?;
    if tld.len() == 2 && SECOND_LEVEL.contains(&second) {
        if let Some(third) = labels.next() {
            return Some(third);
        }
    }
    Some(second)
}

/// The domain a name was registered as: `example.com` for
/// `www.example.com`, `example.co.uk` for `shop.example.co.uk`. `None` for
/// a single-label name.
pub fn registered_domain(qname: &str) -> Option<&str> {
    let label = registered_label(qname)?;
    // The label is a slice of `qname`: the domain starts where it does.
    let start = label.as_ptr() as usize - qname.as_ptr() as usize;
    Some(&qname[start..])
}

/// The DGA score of `label` (mean letter-pair log-probability in
/// hundredths of a bit), or `None` when the label is not one the score
/// suits: internationalized, hyphenated, mostly digits, or too short.
pub fn dga_score(label: &str) -> Option<i32> {
    if label.starts_with("xn--") || label.contains('-') || !label.is_ascii() {
        return None;
    }
    let digits = label.bytes().filter(u8::is_ascii_digit).count();
    if digits > label.len() / 3 {
        return None;
    }
    let symbols: Vec<usize> = std::iter::once(0)
        .chain(
            label
                .bytes()
                .filter(u8::is_ascii_alphabetic)
                .map(|b| (b.to_ascii_lowercase() - b'a') as usize + 1),
        )
        .chain(std::iter::once(0))
        .collect();
    if symbols.len() - 2 < DGA_MIN_LETTERS {
        return None;
    }
    let total: i32 = symbols
        .windows(2)
        .map(|pair| i32::from(BIGRAM_LOG2_CENTI[pair[0]][pair[1]]))
        .sum();
    Some(total / (symbols.len() as i32 - 1))
}

/// Whether `qname`'s registered label looks generated by a DGA.
pub fn is_dga(qname: &str) -> bool {
    registered_label(qname)
        .and_then(dga_score)
        .is_some_and(|score| score < DGA_THRESHOLD_CENTI)
}

