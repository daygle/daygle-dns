#!/usr/bin/env python3
"""Generate crates/daygle-dns-policy/src/dga_model.rs.

The DGA detector scores a domain's registered label by how likely its
letter pairs are in real domain names. This script counts the letter
bigrams (with start and end of label as a 27th symbol) of the registered
labels of a list of popular domains, one per line, and writes the base-2
log-probability table, in hundredths, as Rust.

    python3 scripts/gen-dga-model.py top-1m-domains.txt \
        > crates/daygle-dns-policy/src/dga_model.rs

The shipped table was built from the one million most popular domains
(https://github.com/zer0h/top-1000000-domains).
"""

import math
import sys

# Second-level labels that are part of a country's public suffix
# (example.co.uk), mirrored by `registered_label` in dga.rs.
SECOND_LEVEL = {
    "co", "com", "net", "org", "gov", "edu", "ac", "or", "ne", "go", "gob",
    "nic", "mil", "ltd", "plc", "sch", "nom", "info", "biz", "gen", "web", "in",
}
LETTERS = "abcdefghijklmnopqrstuvwxyz"


def registered_label(domain):
    parts = domain.strip().lower().rstrip(".").split(".")
    if len(parts) < 2:
        return None
    if len(parts) >= 3 and len(parts[-1]) == 2 and parts[-2] in SECOND_LEVEL:
        return parts[-3]
    return parts[-2]


def main(path):
    counts = [[1] * 27 for _ in range(27)]  # add-one smoothing
    with open(path, encoding="utf-8", errors="ignore") as f:
        for line in f:
            label = registered_label(line)
            if not label:
                continue
            symbols = [0] + [LETTERS.index(c) + 1 for c in label if c in LETTERS] + [0]
            for a, b in zip(symbols, symbols[1:]):
                counts[a][b] += 1
    print("//! Generated by scripts/gen-dga-model.py - do not edit by hand.")
    print("//!")
    print("//! Base-2 log-probabilities, in hundredths, of each letter following")
    print("//! another in the registered labels of popular domains. Index 0 is the")
    print("//! start or end of the label, 1..=26 the letters a..=z.")
    print()
    print("#[rustfmt::skip]")
    print("pub const BIGRAM_LOG2_CENTI: [[i16; 27]; 27] = [")
    for row in counts:
        total = sum(row)
        values = ", ".join(str(round(math.log2(c / total) * 100)) for c in row)
        print(f"    [{values}],")
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
